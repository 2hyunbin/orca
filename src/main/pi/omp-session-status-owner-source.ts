import type { PiAgentKind } from '../../shared/pi-agent-kind'
import { ASK_USER_QUESTION_TOOL_NAMES } from '../../shared/agent-question-answered-intent'

export function getSessionSelectionSourceLines(previousOwner = 'ownerPid'): string[] {
  return [
    '  function sessionProvenance(ctx) {',
    '    const manager = ctx?.sessionManager',
    '    return { id: manager?.getSessionId?.(), file: manager?.getSessionFile?.() }',
    '  }',
    '  const scopeKey = JSON.stringify([process.env.ORCA_PANE_KEY, process.env.ORCA_AGENT_LAUNCH_TOKEN])',
    '  const scopesKey = Symbol.for("orca.status-session-registrations")',
    '  const scopes = Reflect.get(globalThis, scopesKey) ?? new Map()',
    '  Reflect.set(globalThis, scopesKey, scopes)',
    `  const scope = scopes.get(scopeKey) ?? { legacy: ${previousOwner} === String(process.pid) || !!Reflect.get(globalThis, Symbol.for("orca.pi.titlebar.owners"))?.has(process.env.ORCA_PANE_KEY), owner: undefined, attention: new Map(), openModals: 0, openAttention: 0 }`,
    '  scopes.set(scopeKey, scope)',
    '',
    '  // Declared roles win; older runtimes select the first start and explicit successors.',
    '  function sessionAuthority(name, event, ctx) {',
    '    if (scope.legacy) return "legacy"',
    '    const lifecycle = name === "session_start" || (isOmpRuntime() && ["session_switch", "session_branch"].includes(name))',
    '    const declared = isOmpRuntime() && lifecycle ? ctx?.agent?.kind : undefined',
    '    if (declared === "sub") return "sub"',
    '    if (ctx?.agent?.kind && declared !== "main") return undefined',
    '    const current = sessionProvenance(ctx)',
    '    if (!current.id) return "legacy"',
    '    if (!lifecycle) return undefined',
    '    const selected = scope.selected',
    '    const transition = selected?.transition',
    '    const successor = !isOmpRuntime() && (["new", "resume", "fork", "reload"].includes(event?.reason) && typeof selected?.file === "string" && event?.previousSessionFile === selected.file ||',
    '      transition && event?.reason === transition.reason && current.file === transition.target && event?.previousSessionFile === transition.from)',
    '    if (current.id === selected?.id) return "main"',
    '    if (declared === "main" || (!selected?.declared && (!selected && name === "session_start" || isOmpRuntime() && name !== "session_start" || successor))) {',
    '      scope.selected = { ...current, declared: declared === "main" }',
    '      return "main"',
    '    }',
    '    return "sub"',
    '  }',
    '  function noteSelectedShutdown(event, ctx) {',
    '    if (!isOmpRuntime() && scope.selected && sessionProvenance(ctx).id === scope.selected.id && ["new", "resume", "fork"].includes(event?.reason)) {',
    '      scope.selected.transition = { reason: event.reason, target: event.targetSessionFile, from: scope.selected.file }',
    '    }',
    '  }'
  ]
}

// OMP loads the same extension in each in-process task session.
export function getOmpSessionOwnerHandlerSourceLines(kind: PiAgentKind): string[] {
  if (kind === 'prime-agent') {
    return [
      '  const authority = "legacy"',
      '  function ownsSessionStatus() { return true }',
      '  function onStatus(name, handler) { pi.on(name, handler) }',
      '  adoptPostQueue()',
      '  activateRoster()'
    ]
  }
  return [
    ...getSessionSelectionSourceLines(),
    '  let authority: "main" | "sub" | "legacy" | "retired" | undefined',
    '  let activated = false',
    `  const source = { id: undefined, post: postChildAttention, retire: retireRegistration, active: () => authority === "main", queue: () => postQueue${kind === 'pi' ? ', ui: () => piUiState' : ''} }`,
    '',
    '  function activateRegistration(ctx): void {',
    '    if (activated) return',
    '    activated = true',
    '    adoptPostQueue()',
    '    activateRoster()',
    '    updateSessionMetadata(ctx)',
    '    updateRuntimeOmpSessionMetadata(ctx)',
    '  }',
    '  function replayAttention(): void {',
    '    for (const pending of scope.attention.values()) {',
    '      for (const record of pending.values()) if (record.open) postChildAttention(record.name, record.extra)',
    '    }',
    '  }',
    '',
    '  function retireRegistration(keepsSession = false): void {',
    '    authority = "retired"',
    '    clearPendingAgentEndCheck()',
    '    if (!keepsSession) clearRunnerExitCheck()',
    '    ompPlanReview?.stopInput()',
    '    ompPlanReview = null',
    '    if (clearAttention() && scope.owner?.active()) scope.owner.post(isOmpRuntime() ? "tool_approval_resolved" : "ui_prompt_end", {})',
    '    if (activated) {',
    '      lifecycleState.onEvent = undefined',
    '      lifecycleState.onRunnerExit = undefined',
    '      lifecycleState.onRunnerExitSettled = undefined',
    '      resetPostQueue()',
    '    }',
    '  }',
    '',
    '  function clearAttention(): boolean {',
    '    const pending = scope.attention.get(source)',
    '    if (!pending) return false',
    '    for (const [surface, record] of pending) if (record.open) {',
    '      scope.openAttention--',
    '      if (surface === "modal" && record.child) scope.openModals--',
    '    }',
    '    scope.attention.delete(source)',
    '    return true',
    '  }',
    '',
    '  function ownsSessionStatus(ctx, name = "", event = undefined): boolean {',
    '    if (authority === "retired") return false',
    '    const next = sessionAuthority(name, event, ctx)',
    '    if (next === "main") {',
    '      const current = sessionProvenance(ctx)',
    '      const sameSession = current.id === scope.owner?.id',
    '      if (scope.owner !== source) {',
    ...(kind === 'pi'
      ? ['        if (sameSession && scope.owner?.ui) piUiState = scope.owner.ui()']
      : []),
    '        if (scope.owner) { postQueue = scope.owner.queue(); scope.owner.retire(sameSession) }',
    '        scope.owner = source',
    '      }',
    '      source.id = current.id',
    '      authority = "main"',
    '      activateRegistration(ctx)',
    '    } else if (!authority && next) {',
    '      authority = next',
    '      if (next === "legacy") {',
    ...(kind === 'pi' ? ['        piUiState = legacyPiUiState'] : []),
    '        activateRegistration(ctx)',
    '      }',
    '    }',
    '    return authority === "main" || authority === "legacy"',
    '  }',
    '',
    '  function isAttention(name, event): boolean {',
    `    const question = isOmpRuntime() ? event?.toolName === "ask" : ${JSON.stringify(ASK_USER_QUESTION_TOOL_NAMES)}.includes(event?.toolName?.replaceAll(/[^a-z0-9]/gi, "").toLowerCase())`,
    '    return name.startsWith("ui_prompt_") || name.startsWith("tool_approval_") || name.startsWith("plan_review_") ||',
    '      (["tool_call", "tool_execution_start", "tool_execution_end"].includes(name) && question)',
    '  }',
    '  function postChildAttention(name, extra): void {',
    '    if (["ui_prompt_end", "tool_execution_end", "tool_approval_resolved", "plan_review_resolved"].includes(name)) {',
    '      if (scope.openAttention > 0) {',
    '        let latest',
    '        for (const pending of scope.attention.values()) for (const record of pending.values()) {',
    '          if (record.open && (!latest || record.order > latest.order)) latest = record',
    '        }',
    '        if (latest) { post(latest.name, latest.extra, false, true); return }',
    '      }',
    '      extra = { ...extra, is_idle: !isTurnInFlight() && !isHeldByChildren() }',
    '    }',
    '    post(name, extra, false, true)',
    '  }',
    '',
    '  function postAttention(name, extra): boolean {',
    '    if (!isAttention(name, { toolName: extra.tool_name })) return false',
    '    const surface = name.startsWith("ui_prompt_") ? "modal" : name.startsWith("plan_review_") ? "plan" : name.startsWith("tool_approval_") ? "approval" : "question"',
    '    const pending = scope.attention.get(source) ?? new Map()',
    '    const open = !["ui_prompt_end", "tool_execution_end", "tool_approval_resolved", "plan_review_resolved"].includes(name)',
    '    const change = Number(open) - Number(pending.get(surface)?.open ?? false)',
    '    scope.openAttention += change',
    '    if (surface === "modal" && source !== scope.owner) scope.openModals += change',
    '    if (open) pending.set(surface, { name, extra, open, child: source !== scope.owner, order: scope.observation = (scope.observation ?? 0) + 1 })',
    '    else pending.delete(surface)',
    '    if (pending.size) scope.attention.set(source, pending)',
    '    else scope.attention.delete(source)',
    '    if (source !== scope.owner && scope.owner?.active()) scope.owner.post(name, extra)',
    '    return source !== scope.owner',
    '  }',
    '',
    '  function onStatus(name, handler): void {',
    '    pi.on(name, (event, ctx) => {',
    '      const wasActivated = activated',
    '      const owns = ownsSessionStatus(ctx, name, event)',
    '      if (authority === "retired") return',
    '      if (name === "agent_start" && clearAttention() && source !== scope.owner && scope.owner?.active()) scope.owner.post(isOmpRuntime() ? "tool_approval_resolved" : "ui_prompt_end", {})',
    '      if (name === "session_shutdown") noteSelectedShutdown(event, ctx)',
    '      if (!owns && (!isAttention(name, event) || (!ctx?.agent?.kind && authority !== "sub"))) {',
    '        if (name === "session_shutdown") retireRegistration()',
    '        return',
    '      }',
    '      const result = handler(event, ctx)',
    '      if (!wasActivated && activated) replayAttention()',
    '      if (name === "session_shutdown" && authority === "main") {',
    '        retireRegistration(event?.reason === "reload" || (event?.reason === "resume" && event?.targetSessionFile === scope.selected?.file))',
    '      }',
    '      return result',
    '    })',
    '  }',
    '',
    ...(kind === 'omp'
      ? ["  onStatus('session_start', (_event, ctx) => { updateRuntimeOmpSessionMetadata(ctx) })"]
      : [])
  ]
}
