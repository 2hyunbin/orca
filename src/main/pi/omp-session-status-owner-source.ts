import type { PiAgentKind } from '../../shared/pi-agent-kind'

// OMP loads the same extension in each in-process task session.
export function getOmpSessionOwnerHandlerSourceLines(kind: PiAgentKind): string[] {
  return [
    '  // SessionManager survives reload/new/resume; task children own a different instance.',
    '  function sessionProvenance(ctx): { manager: unknown; id?: string; file?: string; parent?: string } | undefined {',
    '    const manager = ctx?.sessionManager',
    "    if (!manager || typeof manager !== 'object') return undefined",
    '    const id = typeof manager.getSessionId === "function" ? manager.getSessionId() : undefined',
    '    const file = typeof manager.getSessionFile === "function" ? manager.getSessionFile() : undefined',
    '    const header = typeof manager.getHeader === "function" ? manager.getHeader() : undefined',
    '    return { manager, id, file, parent: typeof header?.parentSession === "string" ? header.parentSession : undefined }',
    '  }',
    '',
    '  function normalizeSessionPath(file): string {',
    '    const normalized = file.replace(/\\\\/g, "/")',
    '    return /^[A-Za-z]:\\//.test(normalized) ? normalized.toLowerCase() : normalized',
    '  }',
    '',
    '  function isNestedTaskTranscript(parentFile, candidateFile): boolean {',
    '    if (typeof parentFile !== "string" || typeof candidateFile !== "string") return false',
    '    const parent = normalizeSessionPath(parentFile)',
    '    const candidate = normalizeSessionPath(candidateFile)',
    '    const root = parent.endsWith(".jsonl") ? parent.slice(0, -6) : parent',
    '    return candidate.startsWith(`${root}/`) && candidate !== parent',
    '  }',
    '',
    '  function legacySessionAuthority(ctx): boolean {',
    '    if (!isOmpRuntime()) return true',
    '    // Preserve the legacy extension-context selector for undeclared runtimes.',
    '    if (ctx?.agentKind === "sub") return false',
    '    const current = sessionProvenance(ctx)',
    '    if (!current) return true',
    "    // A task transcript is never the pane's resumable root, even when its",
    '    // callback arrives before the root session reports on the shared hook.',
    '    if (current.parent) return false',
    '    // Keep ownership through module reload and shutdown while child sessions drain.',
    "    const key = Symbol.for('orca.omp.status-session-owners')",
    '    let owners = Reflect.get(globalThis, key)',
    '    if (!(owners instanceof Map)) {',
    '      owners = new Map()',
    '      Reflect.set(globalThis, key, owners)',
    '    }',
    '    const pane = JSON.stringify([process.env.ORCA_PANE_KEY, process.env.ORCA_AGENT_LAUNCH_TOKEN])',
    '    const owner = owners.get(pane)',
    '    if (owner) {',
    '      if (owner.manager === current.manager) return true',
    '      if (current.parent === owner.file || current.parent === owner.id) return false',
    '      if (isNestedTaskTranscript(owner.file, current.file)) return false',
    '      return false',
    '    }',
    '    owners.set(pane, current)',
    '    return true',
    '  }',
    '',
    '  // Only a session lifecycle declares its role; delegated tool contexts may be sub.',
    '  function selectedSessionAuthority(name, ctx): "main" | "sub" | undefined {',
    '    if (!isOmpRuntime() || !["session_start", "session_switch", "session_branch"].includes(name)) return undefined',
    '    return ctx?.agent?.kind === "main" || ctx?.agent?.kind === "sub" ? ctx.agent.kind : undefined',
    '  }',
    '  let authority: "main" | "sub" | "legacy" | "retired" | undefined',
    '  let activated = false',
    '  const scopeKey = JSON.stringify([process.env.ORCA_PANE_KEY, process.env.ORCA_AGENT_LAUNCH_TOKEN])',
    '  const scopesKey = Symbol.for("orca.status-session-registrations")',
    '  const scopes = Reflect.get(globalThis, scopesKey) ?? new Map()',
    '  Reflect.set(globalThis, scopesKey, scopes)',
    '  const scope = scopes.get(scopeKey) ?? { owner: undefined, attention: new Map() }',
    '  scopes.set(scopeKey, scope)',
    '  const source = { manager: undefined, post: postChildAttention, retire: retireRegistration, active: () => authority === "main", queue: () => postQueue }',
    '',
    '  function activateRegistration(): void {',
    '    if (activated) return',
    '    activated = true',
    '    adoptPostQueue()',
    '    activateRoster()',
    '  }',
    '',
    '  function retireRegistration(): void {',
    '    authority = "retired"',
    '    clearPendingAgentEndCheck()',
    '    clearRunnerExitCheck()',
    '    ompPlanReview?.stopInput()',
    '    ompPlanReview = null',
    '    scope.attention.delete(source)',
    '    if (activated) {',
    '      lifecycleState.onEvent = undefined',
    '      lifecycleState.onRunnerExit = undefined',
    '      lifecycleState.onRunnerExitSettled = undefined',
    '      resetPostQueue()',
    '    }',
    '  }',
    '',
    '  function ownsSessionStatus(ctx, name = ""): boolean {',
    '    if (authority === "retired") return false',
    '    const declared = selectedSessionAuthority(name, ctx)',
    '    if (declared && !authority) {',
    '      authority = declared',
    '      source.manager = ctx.sessionManager',
    '      if (declared === "main") {',
    '        if (scope.owner) { postQueue = scope.owner.queue(); scope.owner.retire() }',
    '        scope.owner = source',
    '        activateRegistration()',
    '      }',
    '    }',
    '    if (authority === "sub") return false',
    '    if (authority === "main") return true',
    '    if (ctx?.agent?.kind) return false',
    // These callbacks were unfiltered on runtimes without a declaration.
    `    const legacyEffect = ["model_select", "session_switch", "session_branch"${kind !== 'pi' ? ', "session_shutdown"' : ''}].includes(name)`,
    '    if (!legacyEffect && !legacySessionAuthority(ctx)) return false',
    '    authority = "legacy"',
    '    activateRegistration()',
    '    return true',
    '  }',
    '',
    '  function isAttention(name, event): boolean {',
    '    return name.startsWith("tool_approval_") || name.startsWith("plan_review_") ||',
    '      (["tool_call", "tool_execution_start", "tool_execution_end"].includes(name) && event?.toolName === "ask")',
    '  }',
    '  function postChildAttention(name, extra): void {',
    '    // Resolving a child overlay does not finish a lead turn or its remaining tasks.',
    '    post(name, name === "plan_review_resolved" ? { ...extra, is_idle: !isTurnInFlight() && !isHeldByChildren() } : extra)',
    '  }',
    '',
    '  function postAttention(name, extra): void {',
    '    if (scope.owner?.active()) { scope.owner.post(name, extra); return }',
    '    const pending = scope.attention.get(source) ?? new Map()',
    '    // One current observation per attention surface; a close replaces its open.',
    '    const surface = name.startsWith("plan_review_") ? "plan" : name.startsWith("tool_approval_") ? "approval" : "ask"',
    '    pending.set(surface, { name, extra })',
    '    scope.attention.set(source, pending)',
    '  }',
    '',
    '  function onStatus(name, handler): void {',
    '    pi.on(name, (event, ctx) => {',
    '      const owns = ownsSessionStatus(ctx, name)',
    '      if (authority === "retired") return',
    '      if (!owns && (!isAttention(name, event) || (!ctx?.agent?.kind && authority !== "sub"))) {',
    '        if (name === "session_shutdown" && authority === "sub") retireRegistration()',
    '        return',
    '      }',
    '      const result = handler(event, ctx)',
    '      if (owns && authority === "main") {',
    '        for (const pending of scope.attention.values()) {',
    '          for (const attention of pending.values()) post(attention.name, attention.extra)',
    '        }',
    '        scope.attention.clear()',
    '      }',
    '      if (name === "session_shutdown" && authority === "main") retireRegistration()',
    '      return result',
    '    })',
    '  }',
    '',
    "  onStatus('session_start', (_event, ctx) => { updateRuntimeOmpSessionMetadata(ctx) })",
    ''
  ]
}
