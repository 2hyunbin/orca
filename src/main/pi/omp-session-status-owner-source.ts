import type { PiAgentKind } from '../../shared/pi-agent-kind'

// OMP loads the same extension in each in-process task session.
export function getOmpSessionOwnerHandlerSourceLines(kind: PiAgentKind): string[] {
  return [
    '  function sessionProvenance(ctx) {',
    '    const manager = ctx?.sessionManager',
    '    return { id: manager?.getSessionId?.(), file: manager?.getSessionFile?.() }',
    '  }',
    '',
    '  // Only a session lifecycle declares its role; delegated tool contexts may be sub.',
    '  function selectedSessionAuthority(name, ctx): "main" | "sub" | undefined {',
    '    if (!isOmpRuntime() || !["session_start", "session_switch", "session_branch"].includes(name)) return undefined',
    '    return ctx?.agent?.kind === "main" || ctx?.agent?.kind === "sub" ? ctx.agent.kind : undefined',
    '  }',
    '  let authority: "main" | "sub" | "legacy" | "retired" | undefined',
    '  let activated = false',
    '  const scopeKey = JSON.stringify([process.env.ORCA_PANE_KEY, process.env.ORCA_AGENT_LAUNCH_TOKEN])',
    '  const scopesKey = Symbol.for("orca.status-session-registrations")',
    '  const scopes = Reflect.get(globalThis, scopesKey) ?? new Map()',
    '  Reflect.set(globalThis, scopesKey, scopes)',
    '  const scope = scopes.get(scopeKey) ?? { owner: undefined, attention: new Map() }',
    '  scopes.set(scopeKey, scope)',
    `  const source = { post: postChildAttention, retire: retireRegistration, active: () => authority === "main", queue: () => postQueue${kind === 'pi' ? ', ui: () => piUiState' : ''} }`,
    '',
    '  function activateRegistration(): void {',
    '    if (activated) return',
    '    activated = true',
    '    adoptPostQueue()',
    '    activateRoster()',
    '  }',
    '',
    '  function retireRegistration(keepsSession = false): void {',
    '    authority = "retired"',
    '    clearPendingAgentEndCheck()',
    '    if (!keepsSession) clearRunnerExitCheck()',
    '    ompPlanReview?.stopInput()',
    '    ompPlanReview = null',
    '    scope.attention.delete(source)',
    '    if (activated) {',
    '      lifecycleState.onEvent = undefined',
    '      lifecycleState.onRunnerExit = undefined',
    '      lifecycleState.onRunnerExitSettled = undefined',
    '      resetPostQueue()',
    '    }',
    '  }',
    '',
    '  // Declared roles win; older runtimes select the first start and explicit successors.',
    '  function sessionAuthority(name, event, ctx) {',
    '    const declared = selectedSessionAuthority(name, ctx)',
    '    if (declared) return declared',
    '    if (ctx?.agent?.kind) return undefined',
    '    const current = sessionProvenance(ctx)',
    '    if (!current.id) return "legacy"',
    '    const selected = scope.selected',
    '    const lifecycle = name === "session_start" || (isOmpRuntime() && ["session_switch", "session_branch"].includes(name))',
    '    if (!lifecycle) return undefined',
    '    if (selected?.declared) return undefined',
    '    if (!selected && name === "session_start") return "main"',
    '    if (current.id === selected?.id) return "main"',
    '    if (isOmpRuntime() && ["session_switch", "session_branch"].includes(name)) return "main"',
    '    if (!isOmpRuntime() && ["new", "resume", "fork", "reload"].includes(event?.reason) &&',
    '        typeof selected?.file === "string" && event?.previousSessionFile === selected.file) return "main"',
    '    return "sub"',
    '  }',
    '',
    '  function ownsSessionStatus(ctx, name = "", event = undefined): boolean {',
    '    if (authority === "retired") return false',
    '    const next = sessionAuthority(name, event, ctx)',
    '    if (next === "main") {',
    '      const current = sessionProvenance(ctx)',
    '      const sameSession = current.id === scope.selected?.id',
    '      if (scope.owner !== source) {',
    ...(kind === 'pi'
      ? ['        if (sameSession && scope.owner?.ui) piUiState = scope.owner.ui()']
      : []),
    '        if (scope.owner) { postQueue = scope.owner.queue(); scope.owner.retire(sameSession) }',
    '        scope.owner = source',
    '      }',
    '      scope.selected = { ...current, declared: !!selectedSessionAuthority(name, ctx) || (sameSession && scope.selected?.declared) }',
    '      authority = "main"',
    '      activateRegistration()',
    '    } else if (!authority && next) {',
    '      authority = next',
    '      if (next === "legacy") {',
    ...(kind === 'pi' ? ['        piUiState = legacyPiUiState'] : []),
    '        activateRegistration()',
    '      }',
    '    }',
    '    return authority === "main" || authority === "legacy"',
    '  }',
    '',
    '  function isAttention(name, event): boolean {',
    '    return name.startsWith("ui_prompt_") || name.startsWith("tool_approval_") || name.startsWith("plan_review_") ||',
    '      (["tool_call", "tool_execution_start", "tool_execution_end"].includes(name) && event?.toolName === "ask")',
    '  }',
    '  function postChildAttention(name, extra): void {',
    '    // Resolving a child overlay does not finish a lead turn or its remaining tasks.',
    ...(kind === 'pi'
      ? [
          '    if (name === "ui_prompt_start") piUiState.depth++',
          '    if (name === "ui_prompt_end") piUiState.depth = Math.max(0, piUiState.depth - 1)'
        ]
      : []),
    '    post(name, ["plan_review_resolved", "ui_prompt_end"].includes(name) ? { ...extra, is_idle: !isTurnInFlight() && !isHeldByChildren() } : extra)',
    '  }',
    '',
    '  function postAttention(name, extra): void {',
    '    if (scope.owner?.active()) { scope.owner.post(name, extra); return }',
    '    const pending = scope.attention.get(source) ?? new Map()',
    '    // One current observation per attention surface; a close replaces its open.',
    '    const surface = name.startsWith("plan_review_") ? "plan" : name.startsWith("tool_approval_") ? "approval" : "ask"',
    '    pending.set(surface, { name, extra })',
    '    scope.attention.set(source, pending)',
    '  }',
    '',
    '  function onStatus(name, handler): void {',
    '    pi.on(name, (event, ctx) => {',
    '      const owns = ownsSessionStatus(ctx, name, event)',
    '      if (authority === "retired") return',
    '      if (!owns && (!isAttention(name, event) || (!ctx?.agent?.kind && authority !== "sub"))) {',
    '        if (name === "session_shutdown") retireRegistration()',
    '        return',
    '      }',
    '      const result = handler(event, ctx)',
    '      if (owns && authority === "main") {',
    '        for (const pending of scope.attention.values()) {',
    '          for (const attention of pending.values()) post(attention.name, attention.extra)',
    '        }',
    '        scope.attention.clear()',
    '      }',
    '      if (name === "session_shutdown" && authority === "main") {',
    '        retireRegistration(event?.reason === "reload" || (event?.reason === "resume" && event?.targetSessionFile === scope.selected?.file))',
    '      }',
    '      return result',
    '    })',
    '  }',
    '',
    "  onStatus('session_start', (_event, ctx) => { updateRuntimeOmpSessionMetadata(ctx) })",
    ''
  ]
}
