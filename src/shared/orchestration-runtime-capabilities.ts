export function resolveFederationProtocolVersion(capabilities: readonly string[] | undefined) {
  if (!capabilities?.includes(ORCHESTRATION_FEDERATION_CONTROL_MAIL_RUNTIME_CAPABILITY)) {
    return 1
  }
  return capabilities.includes(ORCHESTRATION_FEDERATION_LIFECYCLE_SETTLEMENT_RUNTIME_CAPABILITY)
    ? ORCHESTRATION_FEDERATION_LIFECYCLE_SETTLEMENT_PROTOCOL_VERSION
    : ORCHESTRATION_FEDERATION_CONTROL_MAIL_PROTOCOL_VERSION
}

